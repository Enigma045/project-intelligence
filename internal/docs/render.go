package docs

import (
  "fmt"
  "path"
  "sort"
  "strings"

  "pidx/internal/model"
)

type FileEntry struct {
  Path, Language, Hash string
  Size                 int64
  Imports              []string
}

type Input struct {
  Files   []FileEntry
  Symbols []model.Symbol
  Edges   []model.Edge // imports, listens_dom, calls
}

type Output struct {
  Root        string
  Shards      map[string]string // file name -> markdown
  Fingerprint string
}

func moduleOf(p string) string { return path.Dir(p) }

func slug(m string) string {
  if m == "." {
    return "_root"
  }
  return strings.ReplaceAll(m, "/", "__")
}

func usableStatus(s string) bool { return s == "resolved" || s == "inferred" }

// Render is a pure function: index data in, markdown out. Output is deterministic (no timestamps).
func Render(in Input) Output {
  files := append([]FileEntry(nil), in.Files...)
  sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
  var fpb strings.Builder
  for _, f := range files {
    fpb.WriteString(f.Path + "|" + f.Hash + "\n")
  }
  fp := strings.TrimPrefix(model.HashString(fpb.String()), "sha256:")[:12]

  syms := append([]model.Symbol(nil), in.Symbols...)
  sort.Slice(syms, func(i, j int) bool {
    a, b := syms[i], syms[j]
    if a.File != b.File {
      return a.File < b.File
    }
    if a.StartLine != b.StartLine {
      return a.StartLine < b.StartLine
    }
    if a.EndLine != b.EndLine {
      return a.EndLine > b.EndLine
    }
    return a.ID < b.ID
  })
  byFile := map[string][]model.Symbol{}
  byID := map[string]model.Symbol{}
  for _, s := range syms {
    byFile[s.File] = append(byFile[s.File], s)
    byID[s.ID] = s
  }
  edges := append([]model.Edge(nil), in.Edges...)
  sort.Slice(edges, func(i, j int) bool {
    a, b := edges[i], edges[j]
    if a.Type != b.Type {
      return a.Type < b.Type
    }
    if a.Src != b.Src {
      return a.Src < b.Src
    }
    if a.Dst != b.Dst {
      return a.Dst < b.Dst
    }
    return a.Line < b.Line
  })

  type mod struct {
    files []FileEntry
    syms  int
  }
  mods := map[string]*mod{}
  langs := map[string]int{}
  for _, f := range files {
    k := moduleOf(f.Path)
    m := mods[k]
    if m == nil {
      m = &mod{}
      mods[k] = m
    }
    m.files = append(m.files, f)
    m.syms += len(byFile[f.Path])
    langs[f.Language]++
  }
  names := make([]string, 0, len(mods))
  for k := range mods {
    names = append(names, k)
  }
  sort.Strings(names)

  deps := map[string]map[string]int{}
  callsBy := map[string][]string{}
  for _, e := range edges {
    switch {
    case e.Type == "imports" && e.Status == "resolved" && strings.HasPrefix(e.Src, "file:") && strings.HasPrefix(e.Dst, "file:"):
      a, b := moduleOf(e.Src[5:]), moduleOf(e.Dst[5:])
      if a == b {
        continue
      }
      if deps[a] == nil {
        deps[a] = map[string]int{}
      }
      deps[a][b]++
    case e.Type == "calls" && usableStatus(e.Status) && e.Dst != "":
      dup := false
      for _, d := range callsBy[e.Src] {
        if d == e.Dst {
          dup = true
          break
        }
      }
      if !dup {
        callsBy[e.Src] = append(callsBy[e.Src], e.Dst)
      }
    }
  }
  depList := func(m string) []string {
    type kv struct {
      k string
      n int
    }
    var l []kv
    for k, n := range deps[m] {
      l = append(l, kv{k, n})
    }
    sort.Slice(l, func(i, j int) bool {
      if l[i].n != l[j].n {
        return l[i].n > l[j].n
      }
      return l[i].k < l[j].k
    })
    out := make([]string, 0, len(l))
    for _, x := range l {
      out = append(out, x.k)
    }
    return out
  }

  var root strings.Builder
  root.WriteString("# Project map\n\n")
  fmt.Fprintf(&root, "> Generated by pidx, index fingerprint `%s`. Derived data: **source files are authoritative**.\n", fp)
  root.WriteString("> Retrieve code with `pidx source <symbol>`, search with `pidx search <name>`, build task context with `pidx context \"<task>\"`.\n\n")
  root.WriteString("## Overview\n")
  fmt.Fprintf(&root, "- Files: %d, symbols: %d\n", len(files), len(syms))
  type lc struct {
    l string
    n int
  }
  var lcs []lc
  for l, n := range langs {
    lcs = append(lcs, lc{l, n})
  }
  sort.Slice(lcs, func(i, j int) bool {
    if lcs[i].n != lcs[j].n {
      return lcs[i].n > lcs[j].n
    }
    return lcs[i].l < lcs[j].l
  })
  parts := make([]string, 0, len(lcs))
  for _, x := range lcs {
    parts = append(parts, fmt.Sprintf("%s %d", x.l, x.n))
  }
  fmt.Fprintf(&root, "- Languages: %s\n\n", strings.Join(parts, ", "))

  root.WriteString("## Modules\n")
  root.WriteString("| Module | Files | Symbols | Depends on | Detail |\n|---|---|---|---|---|\n")
  for _, m := range names {
    d := depList(m)
    shown := d
    more := ""
    if len(d) > 4 {
      shown = d[:4]
      more = fmt.Sprintf(" +%d", len(d)-4)
    }
    dep := strings.Join(shown, ", ") + more
    if dep == "" {
      dep = "-"
    }
    fmt.Fprintf(&root, "| `%s` | %d | %d | %s | `%s.md` |\n", m, len(mods[m].files), mods[m].syms, dep, slug(m))
  }
  root.WriteString("\nModule detail lives in `.project-intelligence/docs/modules/`.\n\n")

  var entries []string
  for _, s := range syms {
    if s.Kind == "function" && s.Name == "main" && strings.HasSuffix(s.File, ".go") {
      entries = append(entries, fmt.Sprintf("- `main()` at %s:%d", s.File, s.StartLine))
    }
  }
  for _, f := range files {
    if f.Language == "html" {
      entries = append(entries, fmt.Sprintf("- page `%s`", f.Path))
    }
  }
  if len(entries) > 0 {
    if len(entries) > 20 {
      entries = entries[:20]
    }
    root.WriteString("## Entry points\n" + strings.Join(entries, "\n") + "\n\n")
  }

  var flows []string
  for _, e := range edges {
    if e.Type != "listens_dom" || e.Dst == "" || !usableStatus(e.Status) {
      continue
    }
    el, ok1 := byID[e.Src]
    h, ok2 := byID[e.Dst]
    if !ok1 || !ok2 {
      continue
    }
    line := fmt.Sprintf("- `%s` (%s) -> `%s` (%s:%d-%d)", el.Name, el.File, h.Qualified(), h.File, h.StartLine, h.EndLine)
    var cn []string
    for _, c := range callsBy[h.ID] {
      if cs, ok := byID[c]; ok && len(cn) < 6 {
        cn = append(cn, cs.Qualified())
      }
    }
    if len(cn) > 0 {
      line += " -> calls " + strings.Join(cn, ", ")
    }
    flows = append(flows, line)
    if len(flows) >= 25 {
      break
    }
  }
  if len(flows) > 0 {
    root.WriteString("## Web flows (element -> handler -> calls)\n" + strings.Join(flows, "\n") + "\n")
  }

  shards := map[string]string{}
  for _, m := range names {
    var b strings.Builder
    fmt.Fprintf(&b, "# Module `%s`\n\n", m)
    fmt.Fprintf(&b, "> pidx fingerprint `%s`. Derived data; source files are authoritative.\n\n", fp)
    if d := depList(m); len(d) > 0 {
      fmt.Fprintf(&b, "Depends on: %s\n\n", strings.Join(d, ", "))
    }
    for _, f := range mods[m].files {
      fmt.Fprintf(&b, "### `%s` (%s, %.1f KB)\n", f.Path, f.Language, float64(f.Size)/1024)
      if len(f.Imports) > 0 {
        imps := f.Imports
        extra := ""
        if len(imps) > 8 {
          extra = fmt.Sprintf(" +%d", len(imps)-8)
          imps = imps[:8]
        }
        fmt.Fprintf(&b, "imports: %s%s\n", strings.Join(imps, ", "), extra)
      }
      n, skipped := 0, 0
      for _, s := range byFile[f.Path] {
        if s.Kind == "var" || s.Kind == "const" {
          continue
        }
        if n >= 40 {
          skipped++
          continue
        }
        fmt.Fprintf(&b, "- %s  L%d-%d\n", Sig(s), s.StartLine, s.EndLine)
        n++
      }
      if skipped > 0 {
        fmt.Fprintf(&b, "- ... +%d more (`pidx outline %s`)\n", skipped, f.Path)
      }
      b.WriteString("\n")
    }
    shards[slug(m)+".md"] = b.String()
  }
  return Output{Root: root.String(), Shards: shards, Fingerprint: fp}
}
